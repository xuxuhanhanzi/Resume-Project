"""Repair the DABench validation manifest so every task references a frozen table.

Background
----------
`dabench_validation35_v1.json` was generated by picking 35 dev task ids before the
CSV snapshot was finalised. Two of those tasks (`dabench-dev-0066`, `dabench-dev-0070`)
reference `beauty and the labor market.csv`, which is *not* part of the frozen
11-table snapshot. The adapter correctly refuses to run them
(`DABench table is not frozen in this snapshot`), which aborted the whole run.

Fix strategy (minimal + deterministic)
--------------------------------------
1. Keep every manifest task whose table IS frozen (33 of 35).
2. Replace the invalid ones with the lowest-numbered eligible tasks that are
   (a) covered by a frozen table and (b) not already selected.
3. Keep the task count at 35 and record the level distribution for auditability.

The selection is deterministic (sorted by numeric task id), so re-running this
script reproduces the same manifest.
"""

from __future__ import annotations

import argparse
import collections
import json
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
DATA_DIR = (
    REPO_ROOT
    / "evaluation"
    / "benchmarks"
    / "data"
    / "dabench"
    / "b455d578e30fee513abd79936cbdf7a6de026cb5"
)
QUESTIONS = DATA_DIR / "da-dev-questions.jsonl"
DEFAULT_SRC = REPO_ROOT / "evaluation" / "benchmarks" / "manifests" / "dabench_validation35_v1.json"
DEFAULT_DST = REPO_ROOT / "evaluation" / "benchmarks" / "manifests" / "dabench_validation35_v2.json"


def task_id_of(question: dict[str, object]) -> str:
    return f"dabench-dev-{int(str(question['id'])):04d}"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--src", type=Path, default=DEFAULT_SRC)
    parser.add_argument("--dst", type=Path, default=DEFAULT_DST)
    args = parser.parse_args()

    manifest = json.loads(args.src.read_text(encoding="utf-8"))
    frozen_tables = set(manifest["tables"])

    questions = [
        json.loads(line)
        for line in QUESTIONS.read_text(encoding="utf-8").splitlines()
        if line.strip()
    ]
    by_task = {task_id_of(q): q for q in questions}

    original_ids = list(manifest["task_ids"])
    target_count = len(original_ids)

    kept: list[str] = []
    dropped: list[str] = []
    for task_id in original_ids:
        question = by_task.get(task_id)
        if question is None:
            dropped.append(task_id)
            continue
        if str(question["file_name"]) in frozen_tables:
            kept.append(task_id)
        else:
            dropped.append(task_id)

    eligible = sorted(
        (
            task_id
            for task_id, q in by_task.items()
            if str(q["file_name"]) in frozen_tables and task_id not in set(kept)
        ),
        key=lambda t: int(t.rsplit("-", 1)[1]),
    )

    replacements = eligible[: target_count - len(kept)]
    final_ids = sorted(kept + replacements, key=lambda t: int(t.rsplit("-", 1)[1]))

    levels = collections.Counter(str(by_task[t]["level"]) for t in final_ids)
    tables_used = collections.Counter(str(by_task[t]["file_name"]) for t in final_ids)

    manifest["task_ids"] = final_ids
    manifest["schema_version"] = str(manifest.get("schema_version", "1")) + "+fix"
    manifest["repair_note"] = {
        "reason": "original manifest referenced tables outside the frozen snapshot",
        "dropped": dropped,
        "replacements": replacements,
        "level_distribution": dict(sorted(levels.items())),
        "tables_used": dict(sorted(tables_used.items())),
    }

    args.dst.write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")

    print(f"kept          : {len(kept)}")
    print(f"dropped       : {dropped}")
    print(f"replacements  : {replacements}")
    print(f"final tasks   : {len(final_ids)}")
    print(f"levels        : {dict(sorted(levels.items()))}")
    print(f"tables used   : {len(tables_used)}")
    print(f"written       : {args.dst}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
